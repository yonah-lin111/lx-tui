//! 模型身份声明（`# Your Model`）与会话中途切换模型的 `<system-update>` 提示词构建。
//!
//! 对齐 OpenCode (`packages/core/src/plugin/identity.ts` 与 `packages/core/src/session/runner/to-llm-message.ts`)：
//! - 每次请求在系统提示词注入 `# Your Model` 身份段；
//! - 会话中途切换模型或思考等级时，在对应时间线位置向模型注入 `<system-update>`。

use crate::db::chat::ModelSnapshot;

/// 指令源标识：模型本体变更。
pub const SOURCE_CORE_MODEL: &str = "core/model";
/// 指令源标识：思考等级（variant / reasoning effort）变更。
pub const SOURCE_CORE_REASONING_EFFORT: &str = "core/reasoning_effort";
/// 指令源标识：全局或项目 `AGENTS.md` 指令生效。
pub const SOURCE_CORE_AGENTS_MD: &str = "core/agents_md";

/// 当前轮冻结的模型身份描述（用于生成 `# Your Model` 系统提示段）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ModelIdentity {
    /// 面向用户与模型的展示名（如 `DeepSeek V4.1 Flash`）。
    pub display_name: String,
    /// Provider 标识（如 `9router`）。
    pub provider_id: String,
    /// 模型标识（如 `deepseek-v4.1-flash`）。
    pub model_id: String,
    /// 当前思考等级（如 `max` / `high`）；无则为 `None`。
    pub variant: Option<String>,
    /// 该模型是否支持图片输入模态。
    pub supports_image_input: bool,
}

impl ModelIdentity {
    /// 带思考等级后缀的模型展示名（如 `DeepSeek V4.1 Flash (max)`）。
    pub fn label_with_variant(&self) -> String {
        match self.variant.as_deref().filter(|v| !v.is_empty()) {
            Some(variant) => format!("{} ({variant})", self.display_name),
            None => self.display_name.clone(),
        }
    }

    /// 渲染 `# Your Model` 系统提示词段落（全英文，遵守提示词规范）。
    pub fn render_prompt_section(&self) -> String {
        let mut lines = vec![
            "# Your Model".to_string(),
            format!("- Name: {}", self.display_name),
            format!("- Provider ID: {}", self.provider_id),
            format!("- Model ID: {}", self.model_id),
        ];
        if let Some(variant) = self.variant.as_deref().filter(|v| !v.is_empty()) {
            lines.push(format!("- Reasoning Effort / Variant: {variant}"));
        }
        lines.push(format!(
            "- Image Input Support: {}",
            if self.supports_image_input {
                "enabled"
            } else {
                "disabled (historical images are replaced with text placeholders)"
            }
        ));
        lines.join("\n")
    }
}

/// 根据切换前后的模型快照与当前 `AGENTS.md` 状态，计算本次更新涉及的指令源标签列表。
pub fn compute_updated_sources(
    from: Option<&ModelSnapshot>,
    to: &ModelSnapshot,
    has_instructions: bool,
) -> Vec<String> {
    let mut sources = Vec::new();
    match from {
        Some(prev) => {
            if prev.provider != to.provider || prev.model != to.model {
                sources.push(SOURCE_CORE_MODEL.to_string());
            }
            if prev.variant != to.variant {
                sources.push(SOURCE_CORE_REASONING_EFFORT.to_string());
            }
        }
        None => {
            sources.push(SOURCE_CORE_MODEL.to_string());
        }
    }
    if has_instructions {
        sources.push(SOURCE_CORE_AGENTS_MD.to_string());
    }
    sources
}

/// 构造切换模型时注入对话流（以及在时间线卡片展开展示）的英文提示词更新文本。
pub fn render_model_switch_update(
    from_label: Option<&str>,
    to_identity: &ModelIdentity,
    updated_sources: &[String],
    instruction_sources: &[String],
) -> String {
    let mut lines = Vec::new();
    let target_label = to_identity.label_with_variant();
    match from_label.filter(|label| !label.trim().is_empty()) {
        Some(prev) => lines.push(format!(
            "Model switched from {prev} to {target_label}. Earlier assistant turns in this conversation were generated by {prev}; continue the conversation seamlessly as `lx` using your current model."
        )),
        None => lines.push(format!("Active model set to {target_label}.")),
    }
    if !updated_sources.is_empty() {
        lines.push(format!(
            "Instructions updated: {}",
            updated_sources.join(", ")
        ));
    }
    if !instruction_sources.is_empty() {
        lines.push(format!(
            "Active instruction files: {}",
            instruction_sources.join(", ")
        ));
    }
    lines.push(String::new());
    lines.push(to_identity.render_prompt_section());
    lines.join("\n")
}

/// 包装为发给模型的 `<system-update>` 块（转义内部闭合标签防止逃逸）。
pub fn wrap_system_update(content: &str) -> String {
    let safe = content.replace("</system-update>", "&lt;/system-update&gt;");
    format!("<system-update>\n{}\n</system-update>", safe.trim())
}
